/**
 * MOCK DATA - Returns a paginated and filtered slice of MOCK_PROPERTIES.
 * Remove when real DB properties are available.
 */
export function MOCK_PAGINATED_RESPONSE(
  page: number,
  size: number,
  filters?: Pick<
    PropertyFilters,
    'propertyType' | 'country' | 'city' | 'minPrice' | 'maxPrice' | 'minBedrooms' | 'minBathrooms' | 'minGuests' | 'searchText'
  >
): PaginatedPropertyResponse {
  let filtered: PropertyResponse[] = MOCK_PROPERTIES;

  if (filters) {
    const { propertyType, country, city, minPrice, maxPrice, minBedrooms, minBathrooms, minGuests, searchText } = filters;
    if (propertyType) filtered = filtered.filter((p) => p.propertyType === propertyType);
    if (country) filtered = filtered.filter((p) => p.country.toLowerCase().includes(country.toLowerCase()));
    if (city) filtered = filtered.filter((p) => p.city.toLowerCase().includes(city.toLowerCase()));
    if (minPrice !== undefined) filtered = filtered.filter((p) => p.pricePerNight >= minPrice);
    if (maxPrice !== undefined) filtered = filtered.filter((p) => p.pricePerNight <= maxPrice);
    if (minBedrooms !== undefined) filtered = filtered.filter((p) => p.bedrooms >= minBedrooms);
    if (minBathrooms !== undefined) filtered = filtered.filter((p) => p.bathrooms >= minBathrooms);
    if (minGuests !== undefined) filtered = filtered.filter((p) => p.maxGuests >= minGuests);
    if (searchText) {
      const term = searchText.toLowerCase();
      filtered = filtered.filter(
        (p) =>
          p.title.toLowerCase().includes(term) ||
          p.description.toLowerCase().includes(term) ||
          p.city.toLowerCase().includes(term) ||
          p.country.toLowerCase().includes(term)
      );
    }
  }

  const totalElements = filtered.length;
  const totalPages = Math.max(1, Math.ceil(totalElements / size));
  const safePage = Math.min(page, totalPages - 1);
  const start = safePage * size;
  const content = filtered.slice(start, start + size);

  return {
    content,
    page: safePage,
    size,
    totalElements,
    totalPages,
    first: safePage === 0,
    last: safePage >= totalPages - 1,
  };
}
